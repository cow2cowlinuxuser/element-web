// Cross-platform port of rethemendex.sh: on Windows the `sh` found by pnpm may lack `find`/`fgrep`,
// which silently produced an empty _components.pcss and unstyled builds.

import { readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const cssDir = path.dirname(fileURLToPath(import.meta.url));

function findPcss(rel) {
    const found = [];
    for (const entry of readdirSync(path.join(cssDir, rel), { withFileTypes: true })) {
        const relPath = path.posix.join(rel, entry.name);
        if (entry.isDirectory()) {
            found.push(...findPcss(relPath));
        } else if (/^_.*\.pcss$/i.test(entry.name)) {
            found.push(`./${relPath}`);
        }
    }
    return found;
}

const imports = findPcss("")
    .filter((p) => !p.includes("_components.pcss") && !p.includes("_index.pcss"))
    // Byte-wise ordering, matching `LC_ALL=C sort`.
    .sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));

if (imports.length === 0) {
    throw new Error("rethemendex: found no .pcss files, refusing to write an empty _components.pcss");
}

writeFileSync(
    path.join(cssDir, "_components.pcss"),
    ["/* autogenerated by rethemendex.sh */", ...imports.map((p) => `@import "${p}";`), ""].join("\n"),
);
